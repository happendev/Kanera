import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { LOCALES, SOURCE_LOCALE, matchLocale } from "../../../packages/shared/src/locales.ts";

const publicRoot = resolve(import.meta.dirname, "../public");
const directory = resolve(publicRoot, "assets/favicon");
const base = JSON.parse(readFileSync(resolve(directory, "manifest.json"), "utf8"));
const translations = JSON.parse(readFileSync(resolve(import.meta.dirname, "pwa-locales.json"), "utf8"));
const outputs = new Map();
for (const locale of LOCALES) {
  const copy = translations[locale];
  if (!Array.isArray(copy) || copy.length !== 7 || copy.some((value) => typeof value !== "string" || !value.trim())) {
    throw new Error(`Missing PWA translations for ${locale}`);
  }
  const manifest = structuredClone(base);
  manifest.lang = locale;
  manifest.description = copy[0];
  manifest.screenshots.forEach((shot, index) => { shot.label = copy[index + 1]; });
  [manifest.shortcuts[0].name, manifest.shortcuts[0].short_name, manifest.shortcuts[0].description] = copy.slice(4);
  outputs.set(resolve(directory, `manifest.${locale}.json`), JSON.stringify(manifest, null, 2) + "\n");
  delete manifest.share_target;
  outputs.set(resolve(directory, `manifest-samsung.${locale}.json`), JSON.stringify(manifest, null, 2) + "\n");
}
// Run before manifest discovery. Serialize the shared matcher so browser region fallbacks cannot
// drift from Angular's locale loader. Every variant keeps id, scope and start_url unchanged.
outputs.set(resolve(publicRoot, "manifest.js"), `// Generated by scripts/generate-pwa-manifests.mjs.\n(function () {\n  const LOCALES = ${JSON.stringify(LOCALES)};\n  const matchLocale = ${matchLocale.toString()};\n  let stored;\n  try { stored = localStorage.getItem('kanera-locale'); } catch { /* Storage is optional. */ }\n  const locale = LOCALES.includes(stored) ? stored : matchLocale(navigator.languages?.length ? navigator.languages : [navigator.language]) ?? ${JSON.stringify(SOURCE_LOCALE)};\n  const samsung = /Android/.test(navigator.userAgent) && /SamsungBrowser\\//.test(navigator.userAgent);\n  const manifest = document.createElement('link');\n  manifest.rel = 'manifest';\n  manifest.href = '/assets/favicon/manifest' + (samsung ? '-samsung' : '') + '.' + locale + '.json';\n  document.head.appendChild(manifest);\n})();\n`);
for (const [path, content] of outputs) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== content) throw new Error(`${path} is stale; run node scripts/generate-pwa-manifests.mjs`);
  } else writeFileSync(path, content);
}
