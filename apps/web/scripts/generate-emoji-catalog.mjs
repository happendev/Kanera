import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { emojis } from "@tiptap/extension-emoji";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(scriptDir, "../src/app/shared/emoji-catalog.ts");

const emojiPresentation = (emoji) => {
  // Emojibase removes optional variation selectors from `emoji`, while its
  // image filename preserves the canonical display sequence. Reconstructing
  // that sequence keeps text-default symbols such as ⚧ in emoji presentation
  // without shipping or requesting the fallback image at runtime.
  const filename = emoji.fallbackImage?.match(/\/([0-9a-f-]+)\.png$/i)?.[1];
  if (!filename) return emoji.emoji;

  const codepoints = filename.split("-").map((value) => Number.parseInt(value, 16));
  if (codepoints.some((value) => !Number.isInteger(value))) return emoji.emoji;
  return String.fromCodePoint(...codepoints);
};

// Tiptap's source data also carries fallback-image URLs, support versions, and
// emoticon rules. Kanera inserts native Unicode and owns its suggestion UI, so
// those fields add offline bytes without changing editor behaviour.
const rows = emojis
  .filter((emoji) => Boolean(emoji.emoji))
  .map((emoji) => [
    emojiPresentation(emoji),
    emoji.name,
    emoji.shortcodes,
    emoji.tags,
    emoji.group ?? "",
  ]);

