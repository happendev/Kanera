#!/usr/bin/env node
// Writes src/app/core/i18n/workspace-template.messages.ts: one `$localize` message per distinct
// English string in WORKSPACE_TEMPLATES. `$localize` needs literal source text for extraction, so
// the catalog is generated rather than built at runtime. Re-run after editing template content:
//
//   pnpm --filter @kanera/web templates:messages
//
// Node strips the TypeScript types of the shared sources itself (Node 22.18+ / 23.6+).

import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sharedSrc = join(webRoot, "../../packages/shared/src");
const outPath = join(webRoot, "src/app/core/i18n/workspace-template.messages.ts");

const { WORKSPACE_TEMPLATES } = await import(pathToFileURL(join(sharedSrc, "workspace-templates.ts")).href);
const { localizeWorkspaceTemplate } = await import(pathToFileURL(join(sharedSrc, "workspace-template-localize.ts")).href);

/** English text → the kinds of place it appears, in first-seen order. */
const strings = new Map();
for (const template of WORKSPACE_TEMPLATES) {
  localizeWorkspaceTemplate(template, (text, kind) => {
    const kinds = strings.get(text) ?? [];
    if (!kinds.includes(kind)) kinds.push(kind);
    strings.set(text, kinds);
    return text;
  });
}

// Template-literal escaping. A leading ":" would also start $localize metadata, but every message
// carries a description block, so the text after it is always plain.
const escapeText = (text) => text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
// Metadata is `meaning|description` inside the `:...:` block, so neither may contain ":" or "|".
// The meaning gives template content its own message ids: "Done" as a list name and "Done" as a
// button are different words in most languages.
const description = (kinds) => `workspace template content|Workspace template content, ${kinds.join(" and ")}`;

const entries = [...strings].map(
  ([text, kinds]) => `  ${JSON.stringify(text)}: $localize\`:${description(kinds)}:${escapeText(text)}\`,`,
);

const source = `// Generated by apps/web/scripts/generate-template-messages.mjs — do not edit.
// Regenerate with \`pnpm --filter @kanera/web templates:messages\` after changing workspace templates.

/**
 * Translations for the content of the built-in workspace templates (packages/shared/src/workspace-templates.ts),
 * keyed by the English text. Pass \`translateTemplateText\` to \`localizeWorkspaceTemplate\` so a workspace or
 * board created from a template starts in the viewer's language. The API and MCP keep the English templates.
 */
const TEMPLATE_TEXT: Record<string, string> = {
${entries.join("\n")}
};

/** True when the text has a catalog entry; used by the spec that keeps this file in sync. */
export function hasTemplateText(text: string): boolean {
  return Object.hasOwn(TEMPLATE_TEXT, text);
}

/** The viewer's translation of a template string, or the English text when it is not in the catalog. */
export function translateTemplateText(text: string): string {
  return hasTemplateText(text) ? TEMPLATE_TEXT[text]! : text;
}
`;

writeFileSync(outPath, source);
console.log(`Wrote ${strings.size} template messages to ${outPath}`);
