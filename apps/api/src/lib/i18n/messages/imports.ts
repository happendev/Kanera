export function importText(locale: Locale = SOURCE_LOCALE, key: keyof ImportMessages, values: Record<string, string | number> = {}): string {
  const count = values.count;
  const params = { ...values, s: count === 1 ? "" : "s", were: count === 1 ? "was" : "were" };
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => {
    const value = (params as Record<string, string | number>)[name];
    return name === "count" && typeof value === "number" ? new Intl.NumberFormat(locale).format(value) : String(value ?? placeholder);
  });
}
