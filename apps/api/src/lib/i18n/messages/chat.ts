export function chatText(locale: Locale = SOURCE_LOCALE, key: keyof ChatMessages, values: Record<string, string | number> = {}): string {
  // Replace catalog placeholders once; braces in user content are never interpreted as messages.
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}
